export function SeasonDecor({ season }: { season: CycleSeason }) {
  return (
    <div className="season-scene absolute inset-0 z-0" aria-hidden="true" data-season={season}>
      {season === "spring" ? <SpringSkyDecor /> : null}
      {season === "summer" ? <SummerSkyDecor /> : null}
      {season === "spring" || season === "summer"
        ? null
        : Array.from({ length: 8 }).map((_, index) => (
            <span key={index} className="season-particle" />
          ))}
    </div>
  );
}

